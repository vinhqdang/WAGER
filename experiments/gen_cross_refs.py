#!/usr/bin/env python3
"""Generate the cross-document reference tables the two LaTeX documents share.

The manuscript and the supplementary are separate documents, so LaTeX cannot resolve a
reference from one into the other.  Hard-coding the numbers in prose is what this script
exists to replace: it reads each document's .aux file and writes the other document a
lookup table, so `\\suppref{app:proofs}` in the manuscript prints whatever number the
supplementary's proofs section currently has.  Run it between LaTeX passes.

Numbers that cannot be resolved print as `??`, which build.sh greps for.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

MANUSCRIPT = Path(__file__).resolve().parent.parent / "manuscript"

# \newlabel{key}{{printed number}{page}{title}{anchor}{}}
LABEL = re.compile(r"\\newlabel\{([^}]+)\}\{\{([^{}]*)\}")


def read_labels(aux: Path) -> dict[str, str]:
    if not aux.exists():
        return {}
    out: dict[str, str] = {}
    for key, number in LABEL.findall(aux.read_text(encoding="utf-8", errors="replace")):
        # sub-labels such as `foo@cref` carry no printable number we want.
        if key.endswith("@cref") or not number:
            continue
        out.setdefault(key, number)
    return out


def write_table(labels: dict[str, str], macro: str, dest: Path) -> None:
    lines = [
        "%% Generated by experiments/gen_cross_refs.py -- do not edit by hand.",
        "%% Regenerated on every build from the other document's .aux file.",
    ]
    for key in sorted(labels):
        lines.append(rf"\expandafter\gdef\csname {macro}@{key}\endcsname{{{labels[key]}}}")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    pairs = [
        (MANUSCRIPT / "supplementary.aux", "suppref", MANUSCRIPT / "supp-refs.tex"),
        (MANUSCRIPT / "main.aux", "mainref", MANUSCRIPT / "main-refs.tex"),
    ]
    for aux, macro, dest in pairs:
        labels = read_labels(aux)
        write_table(labels, macro, dest)
        print(f"{dest.name}: {len(labels)} labels from {aux.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
