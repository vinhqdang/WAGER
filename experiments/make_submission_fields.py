"""Regenerate manuscript/submission_fields.txt from the manuscript sources.

The submission system asks for the title, abstract, keywords and highlights as
plain text. Deriving them from the LaTeX rather than retyping keeps the pasted
metadata and the compiled paper from drifting apart, and reports the counts the
journal enforces.

Run: conda run -n py313 python experiments/make_submission_fields.py
"""
from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
MS = ROOT / "manuscript"
JOURNAL = "Computational Statistics and Data Analysis (Elsevier)"
ABSTRACT_LIMIT = 250
HL_CHAR_LIMIT = 85


def detex(t: str) -> str:
    t = t.replace("--", "-")
    t = re.sub(r"\\emph\{([^}]*)\}", r"\1", t)
    t = re.sub(r"\$([^$]*)\$", lambda m: m.group(1).replace("\\", ""), t)
    t = t.replace("H\\'ajek", "Hajek").replace("\\'a", "a")
    t = t.replace("\\", "").replace("{", "").replace("}", "")
    return re.sub(r"\s+", " ", t).strip()


abstract = detex((MS / "0abstract.tex").read_text())
main = (MS / "main.tex").read_text()
title = re.search(r"\\title\{(.*?)\}", main).group(1)
kw_block = re.search(r"\\begin\{keyword\}(.*?)\\end\{keyword\}", main, re.S).group(1)
keywords = [k.strip() for k in kw_block.replace("\n", " ").split("\\sep") if k.strip()]
highlights = [l.strip() for l in (MS / "highlights.txt").read_text().splitlines()
              if l.strip() and not l.startswith(("Highlights", "("))]

n_words = len(abstract.split())
flags = []
if n_words > ABSTRACT_LIMIT:
    flags.append(f"ABSTRACT OVER LIMIT: {n_words} > {ABSTRACT_LIMIT}")
if not 1 <= len(keywords) <= 7:
    flags.append(f"KEYWORD COUNT OUT OF RANGE: {len(keywords)}")
if not 3 <= len(highlights) <= 5:
    flags.append(f"HIGHLIGHT COUNT OUT OF RANGE: {len(highlights)}")
for h in highlights:
    if len(h) > HL_CHAR_LIMIT:
        flags.append(f"HIGHLIGHT OVER {HL_CHAR_LIMIT} CHARS ({len(h)}): {h}")

body = f"""SUBMISSION FIELDS -- {JOURNAL}
Generated by experiments/make_submission_fields.py; rerun after editing the abstract,
keywords or highlights.

TITLE
-----
{title}

ABSTRACT ({n_words} words; journal limit {ABSTRACT_LIMIT})
{'-' * 58}
{abstract}

KEYWORDS ({len(keywords)}; journal allows 1-7)
{'-' * 46}
{'; '.join(keywords)}

HIGHLIGHTS ({len(highlights)} bullets; journal allows 3-5, max {HL_CHAR_LIMIT} chars)
{'-' * 66}
""" + "\n".join(f"[{len(h):2d}] {h}" for h in highlights) + f"""

SUGGESTED SECTION
-----------------
Section II - Statistical Methodology for Data Analysis (classification; pattern
recognition; model selection and assessment; cross-validation). Also Section I -
development, evaluation and validation of algorithms.

REVIEW MODEL
------------
Single anonymized: author details appear in the manuscript, not only the title page.

CHECKS
------
{chr(10).join(flags) if flags else 'All journal limits satisfied.'}
"""

(MS / "submission_fields.txt").write_text(body)
print(body)
if flags:
    raise SystemExit(1)
